/**
 * Vendors the finite, official Supercell icon sets — league badges plus clan and
 * player label icons — from api-assets.clashofclans.com into web/public/coc, and
 * regenerates web/src/coc-assets.ts with the ids that landed.
 *
 * Why vendor at all: the API hands back absolute CDN URLs, and hotlinking them
 * breaks the app offline and under a strict CSP. These three sets are small and
 * change only when Supercell adds a league or label, so they are safe to ship.
 *
 * Clan badges are deliberately NOT vendored — there is one per clan, so the set
 * is unbounded. Those stay remote.
 *
 * Usage: COC_API_TOKEN=... node scripts/fetch-coc-assets.mjs
 */
import { mkdir, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const TOKEN = process.env.COC_API_TOKEN
if (!TOKEN) {
  console.error('COC_API_TOKEN is not set. Load it from .env first, e.g.')
  console.error('  set -a && . ./.env && set +a && node scripts/fetch-coc-assets.mjs')
  process.exit(1)
}

const REPO = join(dirname(fileURLToPath(import.meta.url)), '..')
const PUBLIC = join(REPO, 'web/public/coc')
const API = 'https://api.clashofclans.com/v1'

const api = async (path) => {
  const res = await fetch(`${API}${path}`, { headers: { Authorization: `Bearer ${TOKEN}` } })
  // A 403 here almost always means the key is bound to a stale IP, not that the
  // path is wrong — say so, since that is the failure people actually hit.
  if (res.status === 403) throw new Error(`${path} -> 403; mint a key for your current IP`)
  if (!res.ok) throw new Error(`${path} -> HTTP ${res.status}`)
  return res.json()
}

const download = async (url, dest) => {
  const res = await fetch(url)
  if (!res.ok) throw new Error(`${url} -> HTTP ${res.status}`)
  await writeFile(dest, Buffer.from(await res.arrayBuffer()))
}

/** Both label endpoints share one directory; their ids are disjoint (56xxxxxx vs 57xxxxxx). */
const SETS = [
  { key: 'leagues', path: '/leagues?limit=100', dir: 'leagues' },
  { key: 'clanLabels', path: '/labels/clans?limit=100', dir: 'labels' },
  { key: 'playerLabels', path: '/labels/players?limit=100', dir: 'labels' },
]

const manifest = {}
const ids = { leagues: new Set(), labels: new Set() }

for (const set of SETS) {
  const { items } = await api(set.path)
  await mkdir(join(PUBLIC, set.dir), { recursive: true })
  manifest[set.key] = {}

  for (const item of items) {
    const urls = item.iconUrls
    if (!urls) continue
    // Prefer `small` (72px leagues / 64px labels): these render at 24px and 14px
    // respectively, so it clears 3x for retina while `medium` would ship 288px
    // art for a 24px slot — ~70KB per league badge of pure waste. Larger sizes
    // are only a fallback for sets that omit `small`.
    const src = urls.small ?? urls.medium ?? urls.large ?? urls.tiny
    if (!src) continue
    await download(src, join(PUBLIC, set.dir, `${item.id}.png`))
    manifest[set.key][item.id] = { name: item.name, src: `/coc/${set.dir}/${item.id}.png` }
    ids[set.dir].add(item.id)
  }
  console.log(`${set.key}: ${Object.keys(manifest[set.key]).length} icons`)
}

await writeFile(join(PUBLIC, 'manifest.json'), `${JSON.stringify(manifest, null, 2)}\n`)

const list = (set) =>
  [...set]
    .sort((a, b) => a - b)
    .map((id) => `  ${id},`)
    .join('\n')

await writeFile(
  join(REPO, 'web/src/coc-assets.ts'),
  `/*
 * Generated by scripts/fetch-coc-assets.mjs — do not edit by hand.
 *
 * Which league and label icons are vendored under web/public/coc. Anything not
 * in these sets (a league or label added after the last run) falls back to the
 * CDN URL the API supplied, so a stale set degrades to the old behavior rather
 * than a broken image.
 */

const LEAGUE_IDS = new Set([
${list(ids.leagues)}
])

const LABEL_IDS = new Set([
${list(ids.labels)}
])

/** Local league badge when we have it, else the API's CDN URL. */
export function leagueIcon(id: number, remote: string): string {
  return LEAGUE_IDS.has(id) ? \`/coc/leagues/\${id}.png\` : remote
}

/** Local label icon when we have it, else the API's CDN URL. */
export function labelIcon(id: number, remote: string): string {
  return LABEL_IDS.has(id) ? \`/coc/labels/\${id}.png\` : remote
}
`,
)

console.log(`vendored ${ids.leagues.size} leagues + ${ids.labels.size} labels -> web/public/coc`)
console.log('regenerated web/src/coc-assets.ts')
